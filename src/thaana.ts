// Typing Thaana on a keyboard without the Dhivehi layout: the phonetic layout (the one fc-eforms
// uses), on when a field asks for it. Latin letters become Thaana as they are typed or pasted.
export const PHONETIC: Readonly<Record<string, string>> = {
  q: 'ް', w: 'އ', e: 'ެ', r: 'ރ', t: 'ތ', y: 'ޔ', u: 'ު', i: 'ި', o: 'ޮ', p: 'ޕ', a: 'ަ', s: 'ސ', d: 'ދ', f: 'ފ', g: 'ގ', h: 'ހ', j: 'ޖ', k: 'ކ', l: 'ލ',
  z: 'ޒ', x: '×', c: 'ޗ', v: 'ވ', b: 'ބ', n: 'ނ', m: 'މ',
  Q: 'ޤ', W: 'ޢ', E: 'ޭ', R: 'ޜ', T: 'ޓ', Y: 'ޠ', U: 'ޫ', I: 'ީ', O: 'ޯ', P: '÷', A: 'ާ', S: 'ށ', D: 'ޑ', F: 'ﷲ', G: 'ޣ', H: 'ޙ', J: 'ޛ', K: 'ޚ', L: 'ޅ',
  Z: 'ޡ', X: 'ޘ', C: 'ޝ', V: 'ޥ', B: 'ޞ', N: 'ޏ', M: 'ޟ', ',': '،', ';': '؛', '?': '؟',
}

export function toThaana(s: string): string {
  let out = ''
  for (const ch of s) out += PHONETIC[ch] ?? ch
  return out
}
